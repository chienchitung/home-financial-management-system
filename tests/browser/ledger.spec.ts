test('failed save keeps edits; save-and-leave saves both income forms', async ({ page, request }) => {
  await page.goto('/');await page.getByRole('button',{name:'薪資與投資',exact:true}).click();
  await page.getByLabel('本月新投入').fill('2000');
  await page.getByLabel('薪資金額',{exact:true}).fill('70000');
  await page.route('**/api/demo',async route=>{
    if(route.request().method()==='POST')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'儲存暫時失敗，請重試。'})});
    else await route.continue();
  });
  await page.getByRole('button',{name:'總覽',exact:true}).click();
  await page.getByRole('button',{name:'儲存並離開',exact:true}).click();
  await expect(page.locator('.floating-notice').getByRole('alert')).toContainText('儲存暫時失敗');
  await expect(page.getByLabel('本月新投入')).toHaveValue('2000');
  await expect(page.getByLabel('薪資金額',{exact:true})).toHaveValue('70000');
  await page.unroute('**/api/demo');
  await page.getByRole('button',{name:'總覽',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'儲存並離開',exact:true}).click();
  await expect(page.getByRole('heading',{name:'收支總覽',exact:true})).toBeVisible();
  const data=await (await request.get('/api/demo')).json();
  expect(data.investments[data.month].amount).toBe(2000);
  expect(data.totals[data.month].salary).toBe(70000);
});
